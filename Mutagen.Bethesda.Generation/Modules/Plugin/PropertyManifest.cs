using System.Globalization;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using Loqui.Generation;
using Mutagen.Bethesda.Generation.Fields;
using Mutagen.Bethesda.Generation.Modules.Binary;
using Mutagen.Bethesda.Plugins.Meta;
using Noggog;
using ObjectType = Mutagen.Bethesda.Plugins.Meta.ObjectType;

namespace Mutagen.Bethesda.Generation.Modules.Plugin;

/// <summary>
/// C60 (W6): writes, per protocol, a manifest of every object's compiled properties beside its record XML
/// (Manifest\Properties.xml, packed with the XML), from the generator's own model, so a tool doesn't re-derive the
/// generator's rules: each property in compiled order with its type and nullability, where the generated reader reads
/// it (subrecords; a data subrecord's member with its fixed offset and length where the generated reader has one), which
/// hand-written step reads it (from the steps' and Custom fields' fills=, C36/W5), and what a derived property derives
/// from (a &lt;Break/&gt;'s versioning, a data subrecord's state, majorFlag, a property declared hand-written). Property
/// names are the paths' segments of ValuePositionMixIn's positions; step names are its HandRead entries'.
/// </summary>
internal static class PropertyManifest
{
    public const string FileName = "Properties.xml";
    public const string HandWrittenElement = "HandWritten";

    public static async Task Write(ProtocolGeneration proto, BinaryTranslationModule module)
    {
        var objects = proto.ObjectGenerationsByName.Values
            .Where(o => o.GetObjectType() is not (ObjectType.Mod or ObjectType.Group))
            .OrderBy(o => o.Name, StringComparer.Ordinal)
            .ToList();
        if (objects.Count == 0) return;
        var root = new XElement("Manifest",
            new XAttribute("protocol", proto.Protocol.Namespace),
            new XAttribute("namespace", proto.DefaultNamespace));
        foreach (var obj in objects)
        {
            root.Add(await Object(obj, module));
        }
        // A record type of control characters (a group's 0x00000000 label) can't stand in XML text as is
        foreach (var attr in root.DescendantsAndSelf().Attributes())
        {
            if (attr.Value.Any(char.IsControl))
            {
                attr.Value = string.Concat(attr.Value.Select(c => char.IsControl(c) ? $"\\x{(int)c:X2}" : c.ToString()));
            }
        }
        var doc = new XDocument(
            new XComment(" Generated by Mutagen.Bethesda.Generation (PropertyManifest, C60). Do not edit: regenerate. "),
            root);
        var dir = Path.Combine(proto.GenerationFolder.FullName, "..", "Manifest");
        Directory.CreateDirectory(dir);
        var settings = new XmlWriterSettings
        {
            Indent = true,
            IndentChars = "  ",
            Encoding = new UTF8Encoding(false),
            NewLineChars = "\n",
        };
        var path = Path.Combine(dir, FileName);
        using var stream = new MemoryStream();
        using (var writer = XmlWriter.Create(stream, settings))
        {
            doc.Save(writer);
        }
        var bytes = stream.ToArray();
        // Written only when it changes, so an unchanged manifest isn't touched
        if (!File.Exists(path) || !File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes))
        {
            File.WriteAllBytes(path, bytes);
        }
    }

    private static async Task<XElement> Object(ObjectGeneration obj, BinaryTranslationModule module)
    {
        var data = obj.GetObjectData();
        var elem = new XElement("Object", new XAttribute("name", obj.Name));
        if (obj.HasLoquiBaseObject) elem.Add(new XAttribute("baseClass", obj.BaseClass!.Name));
        elem.Add(new XAttribute("objType", obj.GetObjectType().ToString()));
        if (obj.Abstract) elem.Add(new XAttribute("abstract", "true"));
        if (obj.Generics.Count > 0) elem.Add(new XAttribute("generics", string.Join(",", obj.Generics.Keys)));
        if (data.TriggeringRecordTypes.Count > 0)
        {
            elem.Add(new XAttribute("recordTypes", string.Join(",", data.TriggeringRecordTypes.Select(t => t.Type))));
        }
        if (data.CustomBinaryEnd != CustomEnd.Off)
        {
            elem.Add(new XAttribute("customBinaryEnd", data.CustomBinaryEnd.ToString()));
            CopyAttribute(obj.Node, elem, "customBinaryEndFills");
            CopyAttribute(obj.Node, elem, "customBinaryEndWrittenFrom");
        }

        // An object read whole by hand (C73): the method, and the fields it fills
        CopyAttribute(obj.Node, elem, "handRead");
        CopyAttribute(obj.Node, elem, "handReadFills");

        // Which hand-written step fills each field (CustomLogic steps and Custom fields say so with fills=; an object read
        // whole by hand, with handReadFills=)
        var filledBy = new Dictionary<string, string>();
        if ((string?)obj.Node.Attribute("handRead") is { Length: > 0 } handRead
            && (string?)obj.Node.Attribute("handReadFills") is { Length: > 0 } handReadFills)
        {
            foreach (var path in handReadFills.Split(','))
            {
                filledBy.TryAdd(path.Split('.')[0], handRead);
            }
        }
        foreach (var field in obj.IterateFields(expandSets: SetMarkerType.ExpandSets.TrueAndInclude, nonIntegrated: true))
        {
            var fills = (string?)FieldNode(obj, field)?.Attribute("fills");
            if (string.IsNullOrEmpty(fills)) continue;
            foreach (var path in fills.Split(','))
            {
                filledBy.TryAdd(path.Split('.')[0], field.Name);
            }
        }

        // Fixed offsets of the fields the generated reader reads in order from one stretch of bytes (a struct
        // object's fields, a data subrecord's members), as the overlay reader computes them
        // (only what that reader reads itself: a field another step fills has the XML's layoutOffset instead)
        // Keyed by the field itself: Loqui's LoquiType equals any other LoquiType of the same target object, so a value
        // comparer gave every Loqui field of one type in a block the last one's offset (C80, S171)
        var offsets = new Dictionary<TypeGeneration, (int Offset, int? Length)>(ReferenceEqualityComparer.Instance);
        static bool ReadInOrder(TypeGeneration f)
        {
            var d = f.GetFieldData();
            return d.Binary is BinaryGenerationType.Normal or BinaryGenerationType.Custom
                   && d.RecordType == null && !d.HasTrigger;
        }
        if (obj.GetObjectType() != ObjectType.Record)
        {
            await foreach (var len in module.IteratePassedLengths(obj, forOverlay: true, expand: SetMarkerType.ExpandSets.FalseAndInclude))
            {
                if (!ReadInOrder(len.Field)) continue;
                if (FixedOffset(len) is { } off) offsets[len.Field] = (off, len.FieldLength);
            }
        }
        foreach (var dataType in obj.Fields.OfType<DataType>())
        {
            await foreach (var len in module.IteratePassedLengths(obj, dataType.SubFields, forOverlay: true))
            {
                if (len.Field.GetFieldData().Binary is not (BinaryGenerationType.Normal or BinaryGenerationType.Custom)) continue;
                if (FixedOffset(len) is { } off) offsets[len.Field] = (off, len.FieldLength);
            }
        }

        foreach (var field in obj.Fields)
        {
            switch (field)
            {
                case DataType dataType:
                    var dataRecord = dataType.GetFieldData().RecordType?.Type;
                    var breaks = 0;
                    foreach (var sub in dataType.SubFields)
                    {
                        if (sub is BreakType)
                        {
                            elem.Add(new XElement("Break", new XAttribute("index", breaks++), new XAttribute("data", dataRecord ?? "")));
                            continue;
                        }
                        if (Property(obj, sub, filledBy, offsets, dataRecord) is { } p) elem.Add(p);
                    }
                    break;
                case BreakType:
                    elem.Add(new XElement("Break"));
                    break;
                default:
                    if (Property(obj, field, filledBy, offsets, null) is { } prop) elem.Add(prop);
                    break;
            }
        }

        // Members the generator adds beyond the fields
        if (data.MajorRecordFlags)
        {
            elem.Add(new XElement("Property",
                new XAttribute("name", "MajorFlags"),
                new XAttribute("type", $"{obj.ObjectName}.MajorFlag"),
                new XAttribute("derived", "majorFlag"),
                new XAttribute("from", "MajorRecordFlagsRaw")));
        }
        // Properties written by hand beyond the XML, declared on the object (<HandWritten name=... type=... from=.../>)
        foreach (var hand in obj.Node.Elements(XName.Get(HandWrittenElement, LoquiGenerator.Namespace)))
        {
            var p = new XElement("Property", new XAttribute("name", (string)hand.Attribute("name")!));
            foreach (var a in hand.Attributes().Where(a => a.Name.LocalName != "name"))
            {
                p.Add(new XAttribute(a.Name.LocalName, a.Value));
            }
            p.Add(new XAttribute("derived", "handWritten"));
            elem.Add(p);
        }
        return elem;
    }

    private static int? FixedOffset(BinaryTranslationModule.PassedLengths len)
    {
        if (len.PassedType != BinaryTranslationModule.PassedType.Direct) return null;
        if (len.PassedAccessor == null) return 0;
        var s = len.PassedAccessor.Trim();
        if (s.StartsWith("0x") && int.TryParse(s.AsSpan(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hex)) return hex;
        return null;
    }

    private static XElement? Property(
        ObjectGeneration obj,
        TypeGeneration field,
        Dictionary<string, string> filledBy,
        Dictionary<TypeGeneration, (int Offset, int? Length)> offsets,
        string? dataRecord)
    {
        var data = field.GetFieldData();
        if (field is CustomLogic)
        {
            var step = new XElement("Step", new XAttribute("name", field.Name));
            var node = FieldNode(obj, field);
            CopyAttribute(node, step, "fills");
            CopyAttribute(node, step, "writtenFrom");
            if (data.TriggeringRecordTypes.Count > 0)
            {
                step.Add(new XAttribute("subrecords", string.Join(",", data.TriggeringRecordTypes.Select(t => t.Type))));
            }
            if (dataRecord != null) step.Add(new XAttribute("data", dataRecord));
            if (offsets.TryGetValue(field, out var stepAt)) AddOffset(step, stepAt);
            return step;
        }
        if (field is MarkerType or ZeroType)
        {
            var e = new XElement(field is MarkerType ? "Marker" : "Padding");
            if (data.RecordType is { } rt) e.Add(new XAttribute("subrecord", rt.Type));
            if (offsets.TryGetValue(field, out var at)) AddOffset(e, at);
            return e;
        }
        if (!field.IntegrateField || !field.Enabled) return null;
        var p = new XElement("Property",
            new XAttribute("name", field.Name),
            new XAttribute("type", TypeName(field)),
            new XAttribute("field", field.GetType().Name.Replace("Mutagen", "").Replace("Type", "")),
            new XAttribute("nullable", field.Nullable ? "true" : "false"));
        if (field.Name == VersioningModule.VersioningFieldName && data.Binary == BinaryGenerationType.NoGeneration
            && obj.Fields.Any(f => f is BreakType))
        {
            p.Add(new XAttribute("derived", "Break"));
            return p;
        }
        if (obj.Fields.OfType<DataType>().FirstOrDefault(d => d.StateName == field.Name) is { } stateOf)
        {
            p.Add(new XAttribute("derived", "DataType"));
            p.Add(new XAttribute("from", stateOf.GetFieldData().RecordType?.Type ?? ""));
            return p;
        }
        p.Add(new XAttribute("binary", data.Binary.ToString()));
        if (data.TriggeringRecordTypes.Count > 0)
        {
            p.Add(new XAttribute("subrecords", string.Join(",", data.TriggeringRecordTypes.Select(t => t.Type))));
        }
        if (dataRecord != null) p.Add(new XAttribute("data", dataRecord));
        if (offsets.TryGetValue(field, out var fieldAt)) AddOffset(p, fieldAt);
        if (data.Binary == BinaryGenerationType.Custom)
        {
            p.Add(new XAttribute("reader", field.Name));
            var node = FieldNode(obj, field);
            CopyAttribute(node, p, "fills");
            CopyAttribute(node, p, "writtenFrom");
        }
        else if (filledBy.TryGetValue(field.Name, out var step) && step != field.Name)
        {
            p.Add(new XAttribute("filledBy", step));
        }
        if (field.Derivative) p.Add(new XAttribute("derivative", "true"));
        // generateClassMembers="false": the property itself is written by hand
        if (!field.GenerateClassMembers) p.Add(new XAttribute("classMember", "handWritten"));
        return p;
    }

    /// <summary>A field's element in the object's XML (data subrecord members are nested in their Data element)</summary>
    private static XElement? FieldNode(ObjectGeneration obj, TypeGeneration field) =>
        obj.Node.Element(XName.Get("Fields", LoquiGenerator.Namespace))?
            .Descendants()
            .FirstOrDefault(e => (string?)e.Attribute("name") == field.Name);

    private static void AddOffset(XElement e, (int Offset, int? Length) at)
    {
        e.Add(new XAttribute("offset", at.Offset));
        if (at.Length is { } l) e.Add(new XAttribute("length", l));
    }

    private static void CopyAttribute(XElement? from, XElement to, string name)
    {
        if (from?.Attribute(name) is { } a) to.Add(new XAttribute(name, a.Value));
    }

    private static string TypeName(TypeGeneration field)
    {
        try
        {
            return field.TypeName(getter: false);
        }
        catch (Exception)
        {
            return field.GetType().Name;
        }
    }
}
